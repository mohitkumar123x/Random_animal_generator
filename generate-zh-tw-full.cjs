// Generate descriptions based on English description
function generateDescription(animal, zhName) {
  const enDesc = animal.description;
  const category = animal.category;
  
  // Category-specific description templates
  const templates = {
    mammal: `${zhName}是一種${category === 'mammal' ? '哺乳' : ''}動物。${enDesc}`,
    bird: `${zhName}是一種鳥類。${enDesc}`,
    fish: `${zhName}是一種魚類。${enDesc}`,
    reptile: `${zhName}是一種爬行動物。${enDesc}`,
    amphibian: `${zhName}是一種兩棲動物。${enDesc}`,
    insect: `${zhName}是一種昆蟲。${enDesc}`,
    marine: `${zhName}是一種海洋生物。${enDesc}`
  };
  
  return templates[category] || `${zhName}是一種動物。${enDesc}`;
}

const missing = getMissing('zh-TW');
console.log(`zh-TW missing: ${missing.length}`);

// Generate translations
const zhTWNames = {};
for (const animal of missing) {
  const zhName = chineseNames[animal.id] || animal.name.split('-').map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
  const zhDesc = generateDescription(animal, zhName);
  zhTWNames[animal.id] = { name: zhName, description: zhDesc };
}

// Write to file
