// Build funfact-fr.json
const funfactFr = {};
const frEntries = translations.fr || {};
for (const [id, entry] of Object.entries(frEntries)) {
  const animal = animals.find(a => a.id === id);
  const funFact = funFactFr[id] || (animal ? animal.funFact : null);
  funfactFr[id] = {
    name: entry.name,
    description: entry.description,
    ...(funFact ? { funFact } : {})
  };
}

fs.writeFileSync('src/data/funfact-fr.json', JSON.stringify(funfactFr, null, 2));
console.log('funfact-fr.json written with', Object.keys(funfactFr).length, 'entries');

